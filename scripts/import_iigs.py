# Deliberately NOT imported:
#   Apple-IIgs.sv, sys/      MiSTer top level, hps_io, OSD (rtl/gamebub/ instead)
#   pll.v, pll.qip, pll/     Altera PLL (rtl/gamebub/ MMCM instead)
#   dpram_bram.vhd           altsyncram; rtl/gamebub/bram_ce.sv replaces it
#   dpram.sv                 Verilator stand-in for dpram_bram.vhd
#   rom.v                    replaced by the generated rom_*.sv below
#   hdd.v                    no hard disk: stub in rtl/gamebub/iigs_stubs.sv
#   twgs_*.sv                no TransWarp GS: stub in rtl/gamebub/iigs_stubs.sv
#   sdram.sv                 single-word controller, superseded by sdram_burst
#   ddr_trace.v              MiSTer HPS DDR3 debug trace

# ROM images: (module name, address bits, upstream source). Each becomes a
# module with rom.v's ports and timing and its contents as initial
# assignments. The character ROM is generated by a script, the others are hex.
ROMS = [
    ("rom_chr", 12, "vsim/gen_chr.py"),
    ("rom_adb3", 12, "rtl/roms/adb_rom3.hex"),
    ("rom_adb1", 12, "rtl/roms/adb_rom1.hex"),
]


class PatchError(Exception):
    pass


def replace_once(text, old, new, what):
    count = text.count(old)
    if count != 1:
        raise PatchError(f"{what}: expected exactly 1 match, found {count}")
    return text.replace(old, new)


def hex_bytes(path):
    return [int(tok, 16) for tok in path.read_text(encoding="latin-1").split()]


def chr_rom(src):
    """The character ROM, built the way upstream's roms/Makefile builds chr.mem.

    vsim/gen_chr.py is self-contained (the font is embedded) and writes
    chr_iigs.mem into its working directory.
    """
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, "-I", str(src / "vsim" / "gen_chr.py")],
                       cwd=tmp, check=True, stdout=subprocess.DEVNULL)
        return hex_bytes(Path(tmp) / "chr_iigs.mem")


def rom_module(name, aw, values, origin):
    if len(values) != 1 << aw:
        raise PatchError(f"{name}: expected {1 << aw} bytes, found {len(values)}")
    lines = [
        f"// Generated by scripts/import_iigs.py from {origin} - do not edit.\n",
        "// Same ports and timing as upstream rtl/rom.v (synchronous read).\n",
        f"module {name} (\n",
        "\tinput  wire        clock,\n",
        "\tinput  wire        ce,\n",
        "\toutput reg  [7:0]  q,\n",
        f"\tinput  wire [{aw - 1}:0] address\n",
        ");\n",
        f"reg [7:0] d[0:{(1 << aw) - 1}];\n",
        "initial begin\n",
    ]
    lines += [f"\td[{i}] = 8'h{v:02X};\n" for i, v in enumerate(values)]
    lines += [
        "end\n",
        "always @(posedge clock) if (ce) q <= d[address];\n",
        "endmodule\n",
    ]
    return "".join(lines)


def patch_include(include_name):
    """Inline a `include: the framework build passes no include paths."""

    def patch(text, src):
        body = (src / "rtl" / include_name).read_text(encoding="latin-1")
        new = (
            f"// [gamebub] begin inlined {include_name}\n"
            f"{body.rstrip()}\n"
            f"// [gamebub] end inlined {include_name}\n"
        )
        return replace_once(text, f'`include "{include_name}"\n', new, f"`include {include_name}")

    return patch


def patch_iigs(text, src):
    """Slow RAM (banks E0/E1): Quartus builds it from dpram_bram.vhd's
    altsyncram with clock enables on both ports (port B reads only on ce_pix).
    Verilator used dpram.sv, which ignores enable_b. Use bram_ce
    (rtl/gamebub/bram_ce.sv), which keeps both enables, in Vivado and in the
    simulation alike.
    """
    old = (
        "`ifdef VERILATOR\n"
        "dpram #(.widthad_a(17),.prefix(\"slow\"),.p(\" e\")) slowram\n"
        "`else\n"
        "bram #(.widthad_a(17)) slowram\n"
        "`endif\n"
        "(\n"
        "        .clock_a(CLK_14M),\n"
        "        .address_a({bank[0], addr}),\n"
        "        .data_a(dout),\n"
        "        .q_a(slowram_dout),\n"
        "        .wren_a(slowram_we),\n"
        "`ifdef VERILATOR\n"
        "        .ce_a(slowram_ce),\n"
        "`else\n"
        "        .enable_a(slowram_ce),\n"
        "`endif\n"
    )
    new = (
        "// [gamebub] altsyncram equivalent with both clock enables\n"
        "bram_ce #(.widthad_a(17)) slowram\n"
        "(\n"
        "        .clock_a(CLK_14M),\n"
        "        .address_a({bank[0], addr}),\n"
        "        .data_a(dout),\n"
        "        .q_a(slowram_dout),\n"
        "        .wren_a(slowram_we),\n"
        "        .enable_a(slowram_ce),\n"
    )
    text = replace_once(text, old, new, "iigs.sv slowram")
    return patch_iigs_doc_gain(text)


def patch_vgc(text, src):
    text = patch_include("dhr_lut.vh")(text, src)
    return replace_once(
        text,
        'rom #(.memfile("chr.mem"),.AW(12)) charrom(\n',
        "rom_chr charrom( // [gamebub] chr.mem, generated module\n",
        "vgc.v charrom",
    )


def patch_adb(text, src):
    text = replace_once(
        text,
        'rom #(12, 8, "rtl/roms/adb_rom3.hex") adb_rom_inst (\n',
        "rom_adb3 adb_rom_inst ( // [gamebub] adb_rom3.hex, generated module\n",
        "adb.v ROM3 ADB ROM",
    )
    text = replace_once(
        text,
        'rom #(12, 8, "rtl/roms/adb_rom1.hex") adb_rom1_inst (\n',
        "rom_adb1 adb_rom1_inst ( // [gamebub] adb_rom1.hex, generated module\n",
        "adb.v ROM1 ADB ROM",
    )
    # PS/2 has no keypad "=" (Apple keypad, ADB 0x51); the on-screen
    # keyboard (rtl/osk) sends the unused set 2 code 0x0F for it.
    return replace_once(
        text,
        "      9'h00f: ps2_to_apple_key = 8'h7F;  // Invalid\n",
        "      9'h00f: ps2_to_apple_key = 8'h51;  // [gamebub] keypad = (on-screen keyboard)\n",
        "adb.v keypad =",
    )


def patch_prtc(text, src):
    pram = hex_bytes(src / "rtl/roms/pram_init.hex")
    if len(pram) != 256:
        raise PatchError(f"pram_init.hex: expected 256 bytes, found {len(pram)}")
    lines = ["  // [gamebub] rtl/roms/pram_init.hex, inlined by scripts/import_iigs.py\n"]
    lines += [f"  pram[{i}] = 8'h{v:02X};\n" for i, v in enumerate(pram)]
    return replace_once(text, '  $readmemh("rtl/roms/pram_init.hex", pram);\n',
                        "".join(lines), "prtc.v $readmemh")


def patch_default_nettype(text, src):
    """The uart files set `default_nettype none and never restore it. Vivado
    compiles every file in one unit, so the setting would leak into whatever
    file comes next (upstream relies on implicit nets in places)."""
    return text.rstrip("\n") + "\n// [gamebub] restore the default for the files compiled after this one\n`default_nettype wire\n"


def patch_es5503(text, src):
    """`ca` is an output port assigned in an always block but declared as a
    wire; Quartus and Verilator accept that, Vivado rejects it (Synth 8-2577)."""
    return replace_once(text, "    output [3:0]      ca,\n",
                        "    output reg [3:0]  ca,   // [gamebub] reg for Vivado\n", "es5503.v ca")


def patch_iigs_doc_gain(text):
    """A DOC_GAIN input (iigs_core, the "Music Volume" setting) for sound.v."""
    text = replace_once(text,
        "   input              osd_spkr_delay,  // $C05C bit 0 (speaker)\n",
        "   input              osd_spkr_delay,  // $C05C bit 0 (speaker)\n"
        "   input        [2:0] DOC_GAIN,        // [gamebub] sound.v DOC gain, 2 = upstream\n",
        "iigs.sv DOC_GAIN port")
    return replace_once(text,
        "            .speaker_state(speaker_state)\n            );\n",
        "            .speaker_state(speaker_state),\n"
        "            .doc_gain(DOC_GAIN)    // [gamebub]\n            );\n",
        "iigs.sv sound doc_gain")


def patch_sound(text, src):
    """The DOC's filtered output is an average over all 32 oscillator slots,
    so music plays far below full scale; upstream lifts it by a fixed x4 that
    wraps on overflow. Make the shift a port (1 << doc_gain) and saturate,
    here and where the speaker is added."""
    text = replace_once(text,
        "    input             speaker_state);\n",
        "    input             speaker_state,\n"
        "    input [2:0]       doc_gain);   // [gamebub] DOC level x(1 << doc_gain); upstream 2\n",
        "sound.v doc_gain port")
    old = (
        "   wire signed [15:0] iir_boosted_l = iir_sound_out_l <<< 2;\n"
        "   wire signed [15:0] iir_boosted_r = iir_sound_out_r <<< 2;\n"
    )
    new = (
        "   // [gamebub] saturating x(1 << doc_gain)\n"
        "   function automatic signed [15:0] sat16(input signed [23:0] v);\n"
        "      sat16 = (v > 24'sd32767) ? 16'sh7FFF : (v < -24'sd32768) ? 16'sh8000 : v[15:0];\n"
        "   endfunction\n"
        "   wire signed [15:0] iir_boosted_l = sat16($signed({{8{iir_sound_out_l[15]}}, iir_sound_out_l}) <<< doc_gain);\n"
        "   wire signed [15:0] iir_boosted_r = sat16($signed({{8{iir_sound_out_r[15]}}, iir_sound_out_r}) <<< doc_gain);\n"
    )
    text = replace_once(text, old, new, "sound.v boost")
    return replace_once(text,
        "   assign sound_out_l = iir_boosted_l + speaker_audio;\n"
        "   assign sound_out_r = iir_boosted_r + speaker_audio;\n",
        "   assign sound_out_l = sat16(iir_boosted_l + speaker_audio);   // [gamebub] saturate\n"
        "   assign sound_out_r = sat16(iir_boosted_r + speaker_audio);\n",
        "sound.v mix")


def patch_sdram_ch2_read(text):
    """Burst-8 line reads on ch2 (wrl2 = wrh2 = 0), like ch1's.

    On MiSTer ch2 only receives the HPS ROM upload. On Game Bub every file
    (ROMs, WOZ images) arrives through it, and the floppy block device, which
    MiSTer's hps_io served from the SD card, reads and writes the disk images
    in SDRAM through it too (rtl/gamebub/iigs_core.sv). A ch2 read is a
    burst-8 line read like ch1's, into its own 128-bit register (new port
    dout2l), acked at the last beat: one word per round trip made a track load
    (~38 sectors) take ~10 ms, too slow for the ROM's step-and-read seeks.
    (Sharing ch1's `line` is not safe: sdram_cache copies it a synchronizer
    delay after ack1, and a ch2 burst could overwrite it first.) The CPU
    channels and their priority are untouched: ch2 stays last.
    """
    text = replace_once(
        text,
        "    output     [15:0] dout2, input req2, output reg ack2,\n",
        "    output     [15:0] dout2, input req2, output reg ack2,\n"
        "    output     [127:0] dout2l,  // [gamebub] ch2 burst read line\n",
        "sdram_burst dout2l port")
    text = replace_once(
        text,
        "    assign dout1 = line;\n",
        "    assign dout1 = line;\n"
        "    reg [127:0] line2;   // [gamebub] ch2 burst read line\n"
        "    assign dout2l = line2;\n",
        "sdram_burst line2")
    text = replace_once(
        text,
        "                cur <= addr2; wdata <= din2; wdqm <= ~{wrh2,wrl2};\n"
        "                active <= 1; we <= 1; is_read <= 0; serving <= 2'd2; state <= STATE_START;\n",
        "                // [gamebub] no byte enable = burst-8 line read (into line2)\n"
        "                cur <= addr2; wdata <= din2; wdqm <= (wrh2 | wrl2) ? ~{wrh2,wrl2} : 2'b00;\n"
        "                active <= 1; we <= wrh2 | wrl2; is_read <= ~(wrh2 | wrl2); serving <= 2'd2; state <= STATE_START;\n",
        "sdram_burst ch2 dispatch")
    text = replace_once(
        text,
        "            line[ {(state - STATE_LDAT0), 4'b0} +: 16 ] <= dq_in;\n",
        "            line[ {(state - STATE_LDAT0), 4'b0} +: 16 ] <= dq_in;\n"
        "        // [gamebub] ch2 burst read beats\n"
        "        if (mode == MODE_NORMAL && is_read && serving == 2'd2\n"
        "            && state >= STATE_LDAT0 && state <= STATE_LDATL)\n"
        "            line2[ {(state - STATE_LDAT0), 4'b0} +: 16 ] <= dq_in;\n",
        "sdram_burst line2 capture")
    return replace_once(
        text,
        "            if (is_read && serving == 2'd1 && state == STATE_LDATL) ack1 <= req1;\n",
        "            if (is_read && serving == 2'd1 && state == STATE_LDATL) ack1 <= req1;\n"
        "            if (is_read && serving == 2'd2 && state == STATE_LDATL) ack2 <= req2;  // [gamebub]\n",
        "sdram_burst ch2 line ack")


def patch_sdram_burst(text, src):
    """Artix-7 I/O for the SDRAM controller.

    - The framework splits the data bus into dataOut/dataIn/dataDir, so the
      controller drives an explicit output enable instead of a tristate.
    - The inverted SDRAM clock comes from an ODDR (was altddio_out).
    - The data bus output enable rises at the start of a write round.
    """
    text = replace_once(
        text,
        "    inout      [15:0] SDRAM_DQ,\n",
        "    // [gamebub] split data bus: the framework owns the pad tristate\n"
        "    output     [15:0] SDRAM_DQ_OUT,\n"
        "    input      [15:0] SDRAM_DQ_IN,\n"
        "    output            SDRAM_DQ_OE,\n",
        "sdram_burst SDRAM_DQ port",
    )
    text = replace_once(
        text,
        "    assign SDRAM_DQ = dq_oe ? dq_out : 16'bzzzz_zzzz_zzzz_zzzz;\n",
        "    assign SDRAM_DQ_OUT = dq_out;\n"
        "    assign SDRAM_DQ_OE  = dq_oe;\n",
        "sdram_burst tristate",
    )
    text = replace_once(text, "        dq_in <= SDRAM_DQ;\n", "        dq_in <= SDRAM_DQ_IN;\n",
                        "sdram_burst read capture")
    # dq_oe is one register driving 16 pad tristates (the framework has a
    # single dataDir), so it cannot be packed into the I/O blocks, and from
    # the fabric it missed the chip's write setup by 0.3 ns. The chip ignores
    # DQ until the WRITE, so enable the bus from the start of the write round,
    # three clocks early; rtl/gamebub/iigs.xdc makes the path multicycle. No
    # read is in flight then: a read round ends with its last beat long gone.
    text = replace_once(
        text,
        "        dq_oe <= 1'b0;\n",
        "        // [gamebub] bus enabled from STATE_START of a write round (see iigs.xdc)\n"
        "        dq_oe <= (mode == MODE_NORMAL) && active && we && (state >= STATE_START) && (state < STATE_CONT);\n",
        "sdram_burst early dq_oe",
    )
    text = patch_sdram_ch2_read(text)
    start = text.index("    altddio_out #(\n")
    end = text.index(");\n", text.index("sdramclk_ddr (", start)) + len(");\n")
    return text[:start] + (
        "    // [gamebub] SDRAM_CLK = inverted clk (the chip's rising edge is a clk\n"
        "    // falling edge), produced in the output DDR register (was altddio_out).\n"
        "    ODDR #(\n"
        "        .DDR_CLK_EDGE(\"SAME_EDGE\"), .INIT(1'b0), .SRTYPE(\"SYNC\")\n"
        "    ) sdramclk_ddr (\n"
        "        .Q(SDRAM_CLK), .C(clk), .CE(1'b1), .D1(1'b0), .D2(1'b1), .R(1'b0), .S(1'b0)\n"
        "    );\n"
    ) + text[end:]


PATCHES = {
    "rtl/iigs.sv": patch_iigs,
    "rtl/vgc.v": patch_vgc,
    "rtl/adb.v": patch_adb,
    "rtl/prtc.v": patch_prtc,
    "rtl/es5503.v": patch_es5503,
    "rtl/sound.v": patch_sound,
    "rtl/uart/rxuart.v": patch_default_nettype,
    "rtl/uart/txuart.v": patch_default_nettype,
    "rtl/sdram_burst.sv": patch_sdram_burst,
}


def out_name(name):
    """rtl/x/y.v -> x/y.sv; sys/iir_filter.v -> iir_filter.sv"""
    rel = Path(name).relative_to("rtl") if name.startswith("rtl/") else Path(Path(name).name)
    return rel.with_suffix(".sv") if rel.suffix == ".v" else rel


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--src", type=Path, default=ROOT.parent / "Apple-IIgs_MiSTer")
    args = parser.parse_args()

    src = args.src
    if not (src / "rtl" / "iigs.sv").is_file():
        sys.exit(f"MiSTer source not found at {src}")

    try:
        commit = subprocess.check_output(
            ["git", "-C", str(src), "rev-parse", "HEAD"], text=True).strip()
        dirty = subprocess.check_output(
            ["git", "-C", str(src), "status", "--porcelain", "--", "rtl", "sys", "vsim/gen_chr.py"],
            text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        commit, dirty = "unknown", ""

    dst = ROOT / "rtl" / "iigs"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)

    try:
        for name in FILES:
            text = (src / name).read_text(encoding="latin-1")
            if name in PATCHES:
                text = PATCHES[name](text, src)
            # .v -> .sv: Vivado reads .v as strict Verilog-2001 and rejects what
            # Quartus lets through. Verilator, used by the lint and the sim,
            # parses everything as SystemVerilog, so this makes Vivado build
            # what was verified.
            out = dst / out_name(name)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="latin-1")
        for module, aw, origin in ROMS:
            values = chr_rom(src) if origin.endswith(".py") else hex_bytes(src / origin)
            (dst / f"{module}.sv").write_text(rom_module(module, aw, values, origin),
                                              encoding="latin-1")
    except PatchError as e:
        sys.exit(f"Patch failed (upstream changed?): {e}")

    # Not in rtl/: the framework's build passes every file under rtl/ to
    # edalize, which crashes on types other than .v/.sv/.vhdl/.xdc.
    (ROOT / "scripts" / "import_iigs.txt").write_text(
        "rtl/iigs/ is imported by scripts/import_iigs.py - do not edit it by hand.\n"
        "Change the MiSTer source (or the patches in the script) and re-import.\n\n"
        f"source: {os.path.relpath(src.resolve(), ROOT)}\n"
        f"commit: {commit}{' (had uncommitted changes)' if dirty else ''}\n"
    )
    print(f"Imported {len(FILES)} files + {len(ROMS)} ROMs from {commit[:12]} into {dst}")


if __name__ == "__main__":
    main()
