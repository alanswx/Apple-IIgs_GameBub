#!/usr/bin/env python3
"""
Import the Apple IIgs machine RTL from the MiSTer core into rtl/iigs/.

The MiSTer repository (../Apple-IIgs_MiSTer by default) stays the source of
truth for the machine itself. This script copies the files the Game Bub build
needs and applies the small number of platform patches listed in PATCHES
below. Every patch is an exact text match: if upstream changes the text a
patch targets, the import stops with an error instead of silently producing a
different design. Re-run it after pulling MiSTer changes, review the diff,
and commit.

    python3 scripts/import_iigs.py [--src ../Apple-IIgs_MiSTer]

What goes where:
  rtl/iigs/         machine RTL, built by Vivado (every .v/.sv/.vhdl under
                    rtl/ is picked up automatically by the framework build;
                    any other file type there makes the build crash). MiSTer
                    .v files are written as .sv so that Vivado parses them
                    as SystemVerilog, as Verilator does.
  rtl/iigs/rom_*.sv ROM modules generated from upstream's hex images (the
                    framework build cannot $readmemh files: relative paths
                    resolve against the tool's run directory).
  scripts/import_iigs.txt
                    the MiSTer commit the RTL was imported from
"""

